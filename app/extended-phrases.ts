export const extendedLessons = situations.flatMap(({ title, items, sentences }) =>
  items.map(item => {
    const parts = item.split("|");
    return {
      title: `${title}: ${parts[2]}`,
      rows: sentences.map(sentence => sentence.split("|").map((part, index) =>
        part.replaceAll("{", parts[index]).replace(/\s+([?.])/g, "$1")
      ).join("|")),
    };
  })
);
